class AppStrings {
  const AppStrings(this.language);

  final UiLanguage language;

  String call(String key, [Map<String, Object> values = const {}]) {
    var text = (_values[language] ?? _values[UiLanguage.english]!)[key] ?? key;
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return text;
  }

  String ageBandLabel(AgeBand ageBand) => ageBand == AgeBand.allAges
      ? call('age.allAges')
      : call('age.range', {'age': ageBand.value});

  String curriculumTitle(Curriculum curriculum) =>
      language == UiLanguage.chinese ? curriculum.titleZh : curriculum.titleEn;

  String trackTitle(CourseTrack track) =>
      language == UiLanguage.chinese ? track.titleZh : track.titleEn;

  String levelLocation(CourseTrack track, int levelNumber) => call(
    'home.continueDesc',
    {'track': trackTitle(track), 'level': levelNumber},
  );

  String sourceLabel(VocabularySource source, {required CourseTrack track}) {
    if (source.isNce) {
      return call('game.sourceNce', {
        'book': source.book ?? track.order,
        'lesson': source.lesson ?? 0,
      });
    }
    if (source.isKaoyan) {
      return call('game.sourceKaoyan', {
        'track': trackTitle(track),
        'list': source.listId ?? 'NGSL/NAWL 1.2',
      });
    }
    return call('game.sourceIelts', {
      'track': trackTitle(track),
      'list': source.listId ?? 'NAWL 1.2',
    });
  }

