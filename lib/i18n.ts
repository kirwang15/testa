type TranslationParams = Record<string, string | number>;

export function translate(
  language: UiLanguage,
  key: TranslationKey,
  params: TranslationParams = {}
) {
  const template = language === "zh-CN" ? zhCN[key] : messages.en[key];
  return template.replace(/\{(\w+)\}/g, (match, paramName: string) =>
    Object.prototype.hasOwnProperty.call(params, paramName)
      ? String(params[paramName])
      : match
  );
}

export function getTranslationKeys() {
  return Object.keys(messages.en) as TranslationKey[];
}

export function getChineseTranslations(): Readonly<Record<TranslationKey, string>> {
  return zhCN;
}
