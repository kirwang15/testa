export type LevelTranslationKey = keyof typeof levelMessages.en;

export function useLevelI18n() {
  const { language, t: translateBase } = useI18n();
  const t = useCallback(
    (
      key: LevelTranslationKey | TranslationKey,
      params: Record<string, string | number> = {}
    ) => {
      if (!(key in levelMessages.en)) {
        return translateBase(key as TranslationKey, params);
      }
      const template = levelMessages[language][key as LevelTranslationKey];
      return template.replace(/\{(\w+)\}/g, (match, paramName) =>
        Object.prototype.hasOwnProperty.call(params, paramName)
          ? String(params[paramName])
          : match
      );
    },
    [language, translateBase]
  );
  return { language, t };
}
